  assert.doesNotMatch(bottleHand, /launch crew/);
  assert.doesNotMatch(bottleHand, /musette-line/);
  assert.doesNotMatch(bottleHand, /sticky-bottle/);
  assert.doesNotMatch(bottleHand, /bottle-hand-up/);
  assert.doesNotMatch(bottleHand, /bottle crew/);
  assert.doesNotMatch(bottleHand, /treatment-tent/);
  assert.doesNotMatch(bottleHand, /ice-pack-rota/);
