import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const root = resolve(dirname(scriptPath), "..");
const outputPath = resolve(root, "standalone.html");

function lf(value) {
  return value.replace(/\r\n?/gu, "\n");
}

function replaceExactly(source, needle, replacement, label) {
  const first = source.indexOf(needle);
  const last = source.lastIndexOf(needle);
  if (first < 0 || first !== last) throw new Error(`Expected exactly one ${label} marker.`);
  return source.replace(needle, replacement);
}

export async function buildStandalone() {
  const [indexSource, cssSource, modelSource, appSource] = await Promise.all([
    readFile(resolve(root, "index.html"), "utf8"),
    readFile(resolve(root, "styles.css"), "utf8"),
    readFile(resolve(root, "src", "model.js"), "utf8"),
    readFile(resolve(root, "src", "app.js"), "utf8"),
  ]);

  let html = lf(indexSource);
  const css = lf(cssSource).trimEnd();
  const model = lf(modelSource).replace(/^export\s+/gmu, "").trim();
  const app = lf(appSource);
  const importPattern = /^import\s*\{[\s\S]*?\}\s*from\s*["']\.\/model\.js["'];\s*/u;
  const imports = app.match(importPattern);
  if (!imports || imports[0] !== app.match(importPattern)?.[0]) throw new Error("Expected one model import block.");
  const appWithoutImport = app.replace(importPattern, "").trim();
  if (/^\s*(?:import|export)\s/mu.test(`${model}\n${appWithoutImport}`)) {
    throw new Error("Standalone JavaScript still contains a module import or export.");
  }

  const script = `${model}\n\n${appWithoutImport}`;
  if (/<\/script/iu.test(script)) throw new Error("JavaScript contains an unsafe closing script tag.");
  if (/<\/style/iu.test(css)) throw new Error("CSS contains an unsafe closing style tag.");

  const policy = [
    "default-src 'none'",
    "script-src 'unsafe-inline'",
    "style-src 'unsafe-inline'",
    "img-src data: blob:",
    "connect-src 'none'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join("; ");

  html = replaceExactly(
    html,
    '  <meta charset="utf-8">',
    `  <meta charset="utf-8">\n  <meta http-equiv="Content-Security-Policy" content="${policy}">`,
    "charset",
  );
  html = replaceExactly(html, '  <link rel="stylesheet" href="./styles.css">', `  <style>${css}</style>`, "stylesheet");
  html = replaceExactly(
    html,
    '    <p><a href="./MODEL.md">Model notes</a> <span aria-hidden="true">·</span> <a href="./SECURITY.md">Security</a></p>',
    "    <p>Model and security limits are summarized on this page.</p>",
    "repository footer links",
  );
  html = replaceExactly(html, '  <script type="module" src="./src/app.js"></script>', `  <script type="module">${script}</script>`, "application script");
  html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by npm run build:standalone. Edit the source files, not this artifact. -->");
  if (/(?:src|href)=["'](?:\.\/|https?:|\/\/)/iu.test(html)) throw new Error("Standalone HTML contains an external resource reference.");
  return `${html.trimEnd()}\n`;
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    throw new Error("Usage: node scripts/build-standalone.mjs [--check]");
  }
  const output = await buildStandalone();
  if (args[0] === "--check") {
    const current = lf(await readFile(outputPath, "utf8"));
    if (current !== output) throw new Error("standalone.html is stale. Run npm run build:standalone.");
    console.log("standalone.html matches the current source files.");
    return;
  }
  await writeFile(outputPath, output, "utf8");
  console.log(`Built ${outputPath}`);
}

if (process.argv[1] && resolve(process.argv[1]) === scriptPath) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
