import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { clonePreset, computeResidualCoverage, evaluateMarket, validateScenario } from "../src/model.js";

test("canoeing carnival lunch leftover fill is hall pickup and stays distinct from sailing carnival lunch", () => {
  const canoeing = evaluateMarket(clonePreset("canoeingCarnivalLunch"));
  const sailing = evaluateMarket(clonePreset("sailingCarnivalLunch"));
  const rowing = evaluateMarket(clonePreset("rowingCarnivalLunch"));
  const waterPolo = evaluateMarket(clonePreset("waterPoloCarnivalLunch"));
  const softball = evaluateMarket(clonePreset("softballCarnivalLunch"));
  const baseball = evaluateMarket(clonePreset("baseballCarnivalLunch"));
  const hockey = evaluateMarket(clonePreset("hockeyCarnivalLunch"));
  const rugby = evaluateMarket(clonePreset("rugbyCarnivalLunch"));
  const soccer = evaluateMarket(clonePreset("soccerCarnivalLunch"));
  assert.ok(canoeing.winner);
  assert.equal(canoeing.winner.offer.merchant, "Court-side Canoeing Delivery");
  assert.equal(canoeing.winner.offer.fulfillment, "shipping");
  assert.equal(canoeing.winner.fulfilledUnits, 50);
  assert.deepEqual(canoeing.winner.selectedBuyerIds, ["B01", "B02", "B05"]);
  assert.equal(canoeing.scenario.title, "Canoeing carnival lunch");
  assert.notEqual(canoeing.scenario.title, sailing.scenario.title);
  assert.notDeepEqual(clonePreset("canoeingCarnivalLunch"), clonePreset("sailingCarnivalLunch"));
  assert.notDeepEqual(clonePreset("canoeingCarnivalLunch"), clonePreset("rowingCarnivalLunch"));
  assert.notDeepEqual(clonePreset("canoeingCarnivalLunch"), clonePreset("waterPoloCarnivalLunch"));
  assert.notDeepEqual(clonePreset("canoeingCarnivalLunch"), clonePreset("softballCarnivalLunch"));
  assert.notDeepEqual(clonePreset("canoeingCarnivalLunch"), clonePreset("baseballCarnivalLunch"));
  assert.notDeepEqual(clonePreset("canoeingCarnivalLunch"), clonePreset("hockeyCarnivalLunch"));
  assert.notDeepEqual(clonePreset("canoeingCarnivalLunch"), clonePreset("rugbyCarnivalLunch"));
  assert.notDeepEqual(clonePreset("canoeingCarnivalLunch"), clonePreset("soccerCarnivalLunch"));
  const leftoverFill = computeResidualCoverage(canoeing.scenario).secondary;
  assert.ok(leftoverFill);
  assert.equal(leftoverFill.merchant, "Hall Canoeing Pickup");
  const leftoverOffer = canoeing.scenario.offers.find((offer) => offer.id === leftoverFill.offerId);
  assert.equal(leftoverOffer.fulfillment, "pickup");
  assert.equal(leftoverOffer.minimumUnits, 19);
  assert.notEqual(leftoverOffer.unitPrice, leftoverOffer.minimumUnits);
  assert.equal(leftoverOffer.unitPrice, 17);
  assert.equal(canoeing.scenario.buyers.find((buyer) => buyer.id === "B04").maxUnitPrice, 17);
  assert.equal(sailing.scenario.offers.find((offer) => offer.merchant === "Hall Sailing Pickup").minimumUnits, 18);
  assert.equal(rowing.scenario.offers.find((offer) => offer.merchant === "Hall Rowing Pickup").minimumUnits, 17);
  assert.equal(soccer.scenario.offers.find((offer) => offer.merchant === "Hall Soccer Pickup").minimumUnits, 11);
  assert.equal(rugby.scenario.offers.find((offer) => offer.merchant === "Hall Rugby Pickup").minimumUnits, 12);
  assert.equal(hockey.scenario.offers.find((offer) => offer.merchant === "Hall Hockey Pickup").minimumUnits, 13);
  assert.equal(baseball.scenario.offers.find((offer) => offer.merchant === "Hall Baseball Pickup").minimumUnits, 14);
  assert.equal(softball.scenario.offers.find((offer) => offer.merchant === "Hall Softball Pickup").minimumUnits, 15);
  assert.equal(waterPolo.scenario.offers.find((offer) => offer.merchant === "Hall Water Polo Pickup").minimumUnits, 16);
  assert.equal(sailing.winner.offer.merchant, "Court-side Sailing Delivery");
  assert.equal(rowing.winner.offer.merchant, "Court-side Rowing Delivery");
  assert.equal(soccer.winner.offer.merchant, "Court-side Soccer Delivery");
  assert.equal(leftoverOffer.capacity, 44);
  assert.equal(leftoverFill.fulfilledUnits, 23);
  assert.equal(leftoverOffer.capacity - leftoverFill.fulfilledUnits, 21);
  assert.deepEqual(leftoverFill.selectedBuyerIds, ["B03", "B04"]);
  assert.equal(computeResidualCoverage(canoeing.scenario).tertiary, null);
  assert.deepEqual(computeResidualCoverage(canoeing.scenario).leftoverBuyerIds.filter((id) => !(leftoverFill.selectedBuyerIds ?? []).includes(id)), ["B06"]);
  assert.ok(canoeing.results.some((result) => result.offer.merchant === "Court-side Canoeing Delivery" && result.offer.fulfillment === "shipping"));
  assert.ok(canoeing.scenario.buyers.some((buyer) => buyer.allowedVariants.includes("Canoeing pie")));
  assert.ok(canoeing.scenario.buyers.some((buyer) => buyer.allowedVariants.includes("Clubhouse salad")));
  assert.ok(canoeing.scenario.buyers.some((buyer) => buyer.allowedVariants.includes("Clubhouse water")));
  assert.equal(canoeing.scenario.buyers.some((buyer) => buyer.allowedVariants.includes("Sailing pie")), false);
  assert.equal(canoeing.scenario.buyers.some((buyer) => buyer.allowedVariants.includes("Marina water")), false);
  assert.equal(canoeing.scenario.buyers.some((buyer) => buyer.allowedVariants.includes("Marina salad")), false);
  assert.equal(canoeing.scenario.buyers.some((buyer) => buyer.allowedVariants.includes("Rowing pie")), false);
  assert.equal(canoeing.scenario.buyers.some((buyer) => buyer.allowedVariants.includes("Pontoon water")), false);
  const first = evaluateMarket(clonePreset("canoeingCarnivalLunch"));
  const second = evaluateMarket(validateScenario(clonePreset("canoeingCarnivalLunch")));
  assert.equal(first.winner.offer.id, second.winner.offer.id);
  assert.equal(first.winner.fulfilledUnits, second.winner.fulfilledUnits);
  assert.equal(first.winner.fulfilledUnits, 50);
});

test("the example bar includes canoeing carnival lunch next to sailing carnival lunch", async () => {
  const html = await readFile(new URL("../index.html", import.meta.url), "utf8");
  assert.match(html, /data-preset="canoeingCarnivalLunch"/u);
  assert.match(html, /Canoeing carnival/u);
  assert.match(html, /data-preset="sailingCarnivalLunch"/u);
});
