  const triathlon = evaluateMarket(clonePreset("triathlonCarnivalLunch"));
  const surf = evaluateMarket(clonePreset("surfCarnivalLunch"));
  const dragonBoat = evaluateMarket(clonePreset("dragonBoatCarnivalLunch"));
  const kayaking = evaluateMarket(clonePreset("kayakingCarnivalLunch"));
  const canoeing = evaluateMarket(clonePreset("canoeingCarnivalLunch"));
  const sailing = evaluateMarket(clonePreset("sailingCarnivalLunch"));
  const rowing = evaluateMarket(clonePreset("rowingCarnivalLunch"));
  const waterPolo = evaluateMarket(clonePreset("waterPoloCarnivalLunch"));
  const softball = evaluateMarket(clonePreset("softballCarnivalLunch"));
  const baseball = evaluateMarket(clonePreset("baseballCarnivalLunch"));
  const hockey = evaluateMarket(clonePreset("hockeyCarnivalLunch"));
  const rugby = evaluateMarket(clonePreset("rugbyCarnivalLunch"));
  const soccer = evaluateMarket(clonePreset("soccerCarnivalLunch"));
  assert.ok(gravelCycling.winner);
  assert.equal(gravelCycling.winner.offer.merchant, "Court-side Gravel Cycling Delivery");
  assert.equal(gravelCycling.winner.offer.fulfillment, "shipping");
  assert.equal(gravelCycling.winner.fulfilledUnits, 50);
  assert.deepEqual(gravelCycling.winner.selectedBuyerIds, ["B01", "B02", "B05"]);
  assert.equal(gravelCycling.scenario.title, "Gravel cycling carnival lunch");
  assert.notEqual(gravelCycling.scenario.title, trackCycling.scenario.title);
  assert.notEqual(gravelCycling.scenario.title, cycloCross.scenario.title);
  assert.notEqual(gravelCycling.scenario.title, bmx.scenario.title);
  assert.notEqual(gravelCycling.scenario.title, mountainBike.scenario.title);
  assert.notEqual(gravelCycling.scenario.title, cycling.scenario.title);
  assert.notEqual(gravelCycling.scenario.title, triathlon.scenario.title);
  assert.notEqual(gravelCycling.scenario.title, surf.scenario.title);
  assert.notEqual(gravelCycling.scenario.title, dragonBoat.scenario.title);
  assert.notEqual(gravelCycling.scenario.title, kayaking.scenario.title);
  assert.notEqual(gravelCycling.scenario.title, canoeing.scenario.title);
  assert.notEqual(gravelCycling.scenario.title, sailing.scenario.title);
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("trackCyclingCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("cycloCrossCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("bmxCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("mountainBikeCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("cyclingCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("triathlonCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("surfCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("dragonBoatCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("kayakingCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("canoeingCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("sailingCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("rowingCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("waterPoloCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("softballCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("baseballCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("hockeyCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("rugbyCarnivalLunch"));
  assert.notDeepEqual(clonePreset("gravelCyclingCarnivalLunch"), clonePreset("soccerCarnivalLunch"));
  const leftoverFill = computeResidualCoverage(gravelCycling.scenario).secondary;
  assert.ok(leftoverFill);
  assert.equal(leftoverFill.merchant, "Hall Gravel Cycling Pickup");
  const leftoverOffer = gravelCycling.scenario.offers.find((offer) => offer.id === leftoverFill.offerId);
  assert.equal(leftoverOffer.fulfillment, "pickup");
  assert.equal(leftoverOffer.minimumUnits, 29);
  assert.notEqual(leftoverOffer.unitPrice, leftoverOffer.minimumUnits);
  assert.equal(leftoverOffer.unitPrice, 24);
  assert.equal(gravelCycling.scenario.buyers.find((buyer) => buyer.id === "B04").maxUnitPrice, 24);
  assert.equal(gravelCycling.scenario.buyers.find((buyer) => buyer.id === "B04").quantity, 15);
  assert.equal(trackCycling.scenario.offers.find((offer) => offer.merchant === "Hall Track Cycling Pickup").minimumUnits, 28);
  assert.equal(cycloCross.scenario.offers.find((offer) => offer.merchant === "Hall Cyclo-cross Pickup").minimumUnits, 27);
  assert.equal(bmx.scenario.offers.find((offer) => offer.merchant === "Hall BMX Pickup").minimumUnits, 26);
  assert.equal(mountainBike.scenario.offers.find((offer) => offer.merchant === "Hall Mountain Bike Pickup").minimumUnits, 25);
  assert.equal(cycling.scenario.offers.find((offer) => offer.merchant === "Hall Cycling Pickup").minimumUnits, 24);
  assert.equal(triathlon.scenario.offers.find((offer) => offer.merchant === "Hall Triathlon Pickup").minimumUnits, 23);
  assert.equal(surf.scenario.offers.find((offer) => offer.merchant === "Hall Surf Pickup").minimumUnits, 22);
  assert.equal(dragonBoat.scenario.offers.find((offer) => offer.merchant === "Hall Dragon Boat Pickup").minimumUnits, 21);
  assert.equal(kayaking.scenario.offers.find((offer) => offer.merchant === "Hall Kayaking Pickup").minimumUnits, 20);
  assert.equal(canoeing.scenario.offers.find((offer) => offer.merchant === "Hall Canoeing Pickup").minimumUnits, 19);
  assert.equal(sailing.scenario.offers.find((offer) => offer.merchant === "Hall Sailing Pickup").minimumUnits, 18);
  assert.equal(rowing.scenario.offers.find((offer) => offer.merchant === "Hall Rowing Pickup").minimumUnits, 17);
  assert.equal(soccer.scenario.offers.find((offer) => offer.merchant === "Hall Soccer Pickup").minimumUnits, 11);
  assert.equal(rugby.scenario.offers.find((offer) => offer.merchant === "Hall Rugby Pickup").minimumUnits, 12);
  assert.equal(hockey.scenario.offers.find((offer) => offer.merchant === "Hall Hockey Pickup").minimumUnits, 13);
  assert.equal(baseball.scenario.offers.find((offer) => offer.merchant === "Hall Baseball Pickup").minimumUnits, 14);
  assert.equal(softball.scenario.offers.find((offer) => offer.merchant === "Hall Softball Pickup").minimumUnits, 15);
