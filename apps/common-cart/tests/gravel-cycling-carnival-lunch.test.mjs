  assert.equal(leftoverOffer.capacity, 58);
  assert.equal(leftoverFill.fulfilledUnits, 30);
  assert.equal(leftoverOffer.capacity - leftoverFill.fulfilledUnits, 28);
  assert.notEqual(leftoverFill.fulfilledUnits, leftoverOffer.unitPrice);
  assert.notEqual(leftoverFill.fulfilledUnits, leftoverOffer.minimumUnits);
  assert.notEqual(leftoverFill.fulfilledUnits, leftoverOffer.capacity - leftoverFill.fulfilledUnits);
  assert.notEqual(leftoverOffer.capacity, leftoverFill.fulfilledUnits);
  assert.notEqual(leftoverOffer.capacity, leftoverOffer.capacity - leftoverFill.fulfilledUnits);
  assert.notEqual(leftoverOffer.unitPrice, leftoverOffer.capacity - leftoverFill.fulfilledUnits);
  assert.deepEqual(leftoverFill.selectedBuyerIds, ["B03", "B04"]);
  assert.equal(computeResidualCoverage(gravelCycling.scenario).tertiary, null);
  assert.deepEqual(computeResidualCoverage(gravelCycling.scenario).leftoverBuyerIds.filter((id) => !(leftoverFill.selectedBuyerIds ?? []).includes(id)), ["B06"]);
  assert.ok(gravelCycling.results.some((result) => result.offer.merchant === "Court-side Gravel Cycling Delivery" && result.offer.fulfillment === "shipping"));
